"""Bundle the production construction tools and proof grader for isolated replay."""
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
names = ['lessons.js', 'book1-lessons.js', 'euclid-proofs.js', 'book2-lessons.js',
         'books.js', 'course.js', 'construction.js', 'logic.js', 'symbolic.js',
         'book1-logic.js', 'curves.js', 'book2-logic.js', 'guidance.js',
         'book1-ui.js', 'settings.js', 'format-help.js']
parts = [root.joinpath(name).read_text(encoding='utf-8') for name in names]
app = root.joinpath('app.js').read_text(encoding='utf-8').split('installCanvasInput();')[0]
canvas = root.joinpath('canvas-input.js').read_text(encoding='utf-8')
superpose = canvas[canvas.index('function superposeTriangles()'):canvas.index('function activateCanvasPoint')]
parts += [app, superpose]
tail = root.joinpath('supabase/functions/_shared/replay-tail.js').read_text(encoding='utf-8')
# UI wording and preferences must not reset existing competitive records.
model = parts[13][parts[13].index('function nextPointName'):parts[13].index('function bookOneHint')]
progress = parts[14][parts[14].index('function constructionGeometry'):parts[14].index('function suppliedConstruction')]
normalization = parts[15].split('/* Syntax assistance')[0]
def between(source, start, end):
    return source[source.index(start):source.index(end,source.index(start))]
app_model = ''.join(between(app,start,end) for start,end in [
    ('const distance=', '// Lengths'),
    ('function fresh(', 'function load('),
    ('function readableStatement(', 'function triangleStatement('),
    ('function addEdge(', 'function has('),
    ('function referenceAvailable(', 'function selectReference('),
])+app[app.index('function choosePointAction('):]
fingerprint = '\n'.join(parts[:12])+model+progress+normalization+app_model+superpose.split('picks=[];')[0]+tail.split('// Test fixtures')[0]
version = hashlib.sha256(fingerprint.encode()).hexdigest()[:20]
prelude = '''// Generated by scripts/build-ranked-runtime.py. Do not edit.
export const COURSE_VERSION = "__VERSION__";
export function createVerifier(){
const node={textContent:'',hidden:false,addEventListener(){},getScreenCTM(){return {a:1000000,b:0}}};
const document={querySelector(){return node},querySelectorAll(){return []}};
const window={addEventListener(){}};
const localStorage={getItem(){return null}};
const Feedback={use:fn=>fn(),play(){}};
const Ranked={record(){},onRender(){}};
'''.replace('__VERSION__', version)
ending = root.joinpath('supabase/functions/_shared/replay-tail.js').read_text(encoding='utf-8')
target = root/'supabase/functions/_shared/runtime.js'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(prelude+'\n'.join(parts)+'\n'+ending+'\n}\n', encoding='utf-8')
config = root/'online-config.js'
if config.exists():
    import re
    s=config.read_text(encoding='utf-8')
    s=re.sub(r'courseVersion: "[^"]*"',f'courseVersion: "{version}"',s)
    config.write_text(s,encoding='utf-8')
print('Ranked course version:', version)
